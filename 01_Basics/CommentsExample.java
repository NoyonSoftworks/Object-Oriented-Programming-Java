// Java Program to Demonstrate Comments
public class CommentsExample {
    public static void main(String[] args) {

        // This is a single-line comment
        System.out.println("This line will be executed.");

        /*
         * This is a multi-line comment.
         * It can span multiple lines and is ignored by the compiler.
         */
        System.out.println("This line will also be executed.");

        /**
         * This is a documentation comment.
         * It is used to describe the purpose of a class or method.
         * You can generate documentation using the javadoc tool.
         */
        System.out.println("Java supports 3 types of comments!");
    }
}
